-- Public crop-value ranking (no farmer data needed):
CREATE OR REPLACE VIEW crop_value_summary AS
SELECT crop_name,
       COUNT(*) AS channels,
       COUNT(*) FILTER (WHERE value_level='High')   AS high_value,
       COUNT(*) FILTER (WHERE value_level='Medium') AS medium_value,
       COUNT(*) FILTER (WHERE value_level='Low')    AS low_value,
       ROUND(100.0*(3*COUNT(*) FILTER (WHERE value_level='High')
                  + 2*COUNT(*) FILTER (WHERE value_level='Medium')
                  +   COUNT(*) FILTER (WHERE value_level='Low')) / (3*COUNT(*)),0) AS value_score
FROM crop_value_chain GROUP BY crop_name ORDER BY value_score DESC, channels DESC;
