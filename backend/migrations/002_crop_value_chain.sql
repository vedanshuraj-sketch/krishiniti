CREATE TABLE IF NOT EXISTS crop_value_chain (
  id SERIAL PRIMARY KEY,
  crop_name VARCHAR(100) NOT NULL,
  botanical_name VARCHAR(150),
  plant_part VARCHAR(120) NOT NULL,
  industry VARCHAR(80) NOT NULL,
  product VARCHAR(200) NOT NULL,
  value_level VARCHAR(20) NOT NULL CHECK (value_level IN ('High','Medium','Low')),
  buyer_type VARCHAR(80) NOT NULL,
  processing_required BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP DEFAULT NOW(),
  UNIQUE (crop_name, plant_part, industry, product, buyer_type)
);
CREATE INDEX IF NOT EXISTS idx_crop_value_chain_crop ON crop_value_chain (crop_name);

